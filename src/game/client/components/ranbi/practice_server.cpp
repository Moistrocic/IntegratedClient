// task-84: dedicated port file so this server can coexist with the tutorial/main-menu
// CLocalServer (which uses "local_server_port.<pid>.txt"). The file name is relative to the
// user storage directory and contains no spaces.
static const char *PracticePortFile(char *pBuf, unsigned BufSize)
{
	str_format(pBuf, BufSize, "ranbi_practice_port.%d.txt", process_id());
	return pBuf;
}

// task-86 (optional R5 cleanup): remove only files generated by *this* process id from a
// previous crashed session. Files of other client processes (other pids) are left untouched.
struct SStalePracticeFiles
{
	IStorage *m_pStorage;
	int m_Pid;
	int m_Removed;
};

static int StalePracticeFilesCallback(const char *pName, int IsDir, int Type, void *pUser)
{
	(void)Type;
	if(IsDir)
		return 0;
	SStalePracticeFiles *pData = static_cast<SStalePracticeFiles *>(pUser);
	char aPrefix[64];
	str_format(aPrefix, sizeof(aPrefix), "ranbi_practice_%d_", pData->m_Pid);
	if(!str_startswith(pName, aPrefix))
		return 0;
	char aPath[IO_MAX_PATH_LENGTH];
	str_format(aPath, sizeof(aPath), "maps/%s", pName);
	if(pData->m_pStorage->RemoveFile(aPath, IStorage::TYPE_SAVE))
		pData->m_Removed++;
	return 0;
}

void CRanbiFastPractice::SetError(const char *pError)
{
	str_copy(m_aLastError, pError && pError[0] ? pError : "unknown practice server error", sizeof(m_aLastError));
	dbg_msg("ranbi_practice", "%s", m_aLastError);
	// Development warning in the in-game console/chat; feature flag defaults to off.
}

bool CRanbiFastPractice::ProcessAlive() const
{
#if defined(CONF_PLATFORM_ANDROID)
	return false;
#else
	return m_Process != INVALID_PROCESS && process_is_alive(m_Process);
#endif
}

bool CRanbiFastPractice::IsServerRunning() const
{
	return ProcessAlive() && m_Port > 0;
}

bool CRanbiFastPractice::IsServerStarting() const
{
	return ProcessAlive() && m_WaitingForPort;
}

void CRanbiFastPractice::CloseJobObject()
{
#if defined(CONF_FAMILY_WINDOWS)
	if(m_pJobObject != nullptr)
	{
		CloseHandle(static_cast<HANDLE>(m_pJobObject));
		m_pJobObject = nullptr;
	}
#else
	m_pJobObject = nullptr;
#endif
}

bool CRanbiFastPractice::RemovePathWithRetry(const char *pPath, int Attempts)
{
	if(pPath == nullptr || pPath[0] == '\0')
		return true;
	for(int Attempt = 0; Attempt < Attempts; Attempt++)
	{
		if(!Storage()->FileExists(pPath, IStorage::TYPE_SAVE))
			return true;
		if(Storage()->RemoveFile(pPath, IStorage::TYPE_SAVE))
			return true;
		if(Attempt + 1 < Attempts)
			std::this_thread::sleep_for(std::chrono::milliseconds(25));
	}
	return !Storage()->FileExists(pPath, IStorage::TYPE_SAVE);
}

bool CRanbiFastPractice::CleanupTempFiles(int Attempts)
{
	bool Ok = true;
	if(m_aMapPath[0] != '\0')
	{
		if(RemovePathWithRetry(m_aMapPath, Attempts))
			m_aMapPath[0] = '\0';
		else
			Ok = false;
	}
	if(m_aMapCfgPath[0] != '\0')
	{
		if(RemovePathWithRetry(m_aMapCfgPath, Attempts))
			m_aMapCfgPath[0] = '\0';
		else
			Ok = false;
	}
	if(m_aPortFile[0] != '\0')
	{
		if(RemovePathWithRetry(m_aPortFile, Attempts))
			m_aPortFile[0] = '\0';
		else
			Ok = false;
	}
	if(m_aGuestSyncFile[0] != '\0')
	{
		if(Storage()->RemoveFile(m_aGuestSyncFile, IStorage::TYPE_ABSOLUTE))
			m_aGuestSyncFile[0] = '\0';
		else
			Ok = false;
	}
	if(Ok || (m_aMapPath[0] == '\0' && m_aMapCfgPath[0] == '\0'))
		m_aMapName[0] = '\0';

	m_CleanupPending = !Ok;
	if(!Ok)
		m_CleanupRetryTime = time_get_nanoseconds() + std::chrono::milliseconds(500);
	return Ok;
}

void CRanbiFastPractice::RetryPendingCleanup()
{
	if(!m_CleanupPending)
		return;
	const auto Now = time_get_nanoseconds();
	if(Now < m_CleanupRetryTime)
		return;
	const bool Cleaned = CleanupTempFiles(1);
	if(Cleaned)
		dbg_msg("ranbi_practice", "pending temporary practice files cleaned up");
}

bool CRanbiFastPractice::StopProcess()
{
#if defined(CONF_PLATFORM_ANDROID)
	return true;
#elif defined(CONF_FAMILY_WINDOWS)
	if(m_Process == INVALID_PROCESS)
	{
		CloseJobObject();
		return true;
	}
	HANDLE pProcess = static_cast<HANDLE>(m_Process);
	DWORD ExitCode = 0;
	if(GetExitCodeProcess(pProcess, &ExitCode) && ExitCode != STILL_ACTIVE)
	{
		CloseHandle(pProcess);
		m_Process = INVALID_PROCESS;
		CloseJobObject();
		return true;
	}
	if(!TerminateProcess(pProcess, 0))
		dbg_msg("ranbi_practice", "warning: TerminateProcess failed for practice server; trying job fallback");
	DWORD WaitResult = WaitForSingleObject(pProcess, 250);
	if(WaitResult != WAIT_OBJECT_0)
	{
		// Bounded fallback: closing the kill-on-close job must terminate the server.
		dbg_msg("ranbi_practice", "warning: practice server still running after terminate; closing job object");
		CloseJobObject();
		WaitResult = WaitForSingleObject(pProcess, 250);
	}
	if(WaitResult == WAIT_OBJECT_0)
	{
		CloseHandle(pProcess);
		m_Process = INVALID_PROCESS;
		CloseJobObject();
		return true;
	}
	// Keep the handle instead of closing it and leaking an untracked orphan. OnShutdown calls
	// StopServer(true) which retries and the job object is the final fallback.
	dbg_msg("ranbi_practice", "warning: practice server did not exit within bounded wait; keeping process handle");
	return false;
#else
	if(m_Process == INVALID_PROCESS)
		return true;
	const bool Killed = process_kill(m_Process) != 0;
	if(Killed || !process_is_alive(m_Process))
	{
		m_Process = INVALID_PROCESS;
		CloseJobObject();
		return true;
	}
	// process_kill has no portable wait/job fallback here; retain the handle so a later retry
	// or OnShutdown does not silently forget the process.
	dbg_msg("ranbi_practice", "warning: could not kill practice server; keeping process handle for retry");
	return false;
#endif
}

void CRanbiFastPractice::ReapExitedProcess()
{
#if !defined(CONF_PLATFORM_ANDROID)
	if(m_Process == INVALID_PROCESS)
		return;
	if(process_is_alive(m_Process))
		return;
#if defined(CONF_FAMILY_WINDOWS)
	CloseHandle(static_cast<HANDLE>(m_Process));
#endif
	m_Process = INVALID_PROCESS;
	m_KillFailed = false;
	CloseJobObject();
#endif
}

void CRanbiFastPractice::CleanupStalePidFiles()
{
	// Optional task-86 cleanup: only this process id's stale map/cfg files.
	SStalePracticeFiles Data{Storage(), process_id(), 0};
	Storage()->ListDirectory(IStorage::TYPE_SAVE, "maps", StalePracticeFilesCallback, &Data);

	char aPortFile[128];
	PracticePortFile(aPortFile, sizeof(aPortFile));
	Storage()->RemoveFile(aPortFile, IStorage::TYPE_SAVE);

	if(Data.m_Removed > 0)
		dbg_msg("ranbi_practice", "removed %d stale practice file(s) from a previous session", Data.m_Removed);
}

void CRanbiFastPractice::StopServer(bool Shutdown)
{
	StopClientB();
	CleanupChatFiles();
#if !defined(CONF_PLATFORM_ANDROID)
	if(m_Process != INVALID_PROCESS && (!m_KillFailed || Shutdown))
	{
		if(StopProcess())
			m_KillFailed = false;
		else
			m_KillFailed = true;
	}
#endif
	ReapExitedProcess();
	if(m_Process == INVALID_PROCESS)
		CloseJobObject();

	// Wait is bounded above (up to 2 x 250 ms only when a live process existed); file deletion
	// is retried because Windows may release server-opened files slightly after termination.
	const bool Cleaned = CleanupTempFiles(Shutdown ? 5 : 2);
	if(!Cleaned)
	{
		dbg_msg("ranbi_practice", "warning: temporary practice files still locked; will retry");
	}

	m_Port = 0;
	m_WaitingForPort = false;
	m_StartTime = std::chrono::nanoseconds(0);
	m_NextPortCheck = std::chrono::nanoseconds(0);
}

void CRanbiFastPractice::OnStateChange(int NewState, int OldState)
{
	const bool WasOnline = m_Online;
	m_Online = NewState == IClient::STATE_ONLINE;

	if(NewState == IClient::STATE_OFFLINE && OldState == IClient::STATE_ONLINE)
	{
		// A real leave from a connected server (not the initial connect/loading states).
		// Turning the feature off also updates the menu button label.
		g_Config.m_RcRanbiFastPractice = 0;
		m_WasEnabled = false;
		m_StartAttempted = false;
		StopServer();
		dbg_msg("ranbi_practice", "auto-disabled on disconnect");
		return;
	}

	if(!m_Online)
	{
		// Initial connect/loading/other transient states: never flip the config here.
		StopServer();
		m_StartAttempted = false;
		return;
	}
	if(m_Online && !WasOnline)
	{
		// A new server connection/map: allow one start attempt for this session.
		m_StartAttempted = false;
	}
}

void CRanbiFastPractice::OnReset()
{
	m_Online = false;
	m_StartAttempted = false;
	StopServer();
}

void CRanbiFastPractice::OnMapLoad()
{
	// The main client is loading a new map; any previous temporary map belongs to the old map.
	m_StartAttempted = false;
	StopServer();
}

void CRanbiFastPractice::OnShutdown()
{
	// Must run before the client process exits so no DDNet-Server.exe is left behind.
	g_Config.m_RcRanbiFastPractice = 0;
	m_WasEnabled = false;
	// Force a final kill retry even if a previous bounded StopProcess attempt failed.
	StopServer(true);
}

void CRanbiFastPractice::UpdatePort()
{
	if(!m_WaitingForPort)
		return;

	const auto Now = time_get_nanoseconds();
	if(Now < m_NextPortCheck)
		return;
	m_NextPortCheck = Now + std::chrono::milliseconds(100);

	char *pPort = Storage()->ReadFileStr(m_aPortFile, IStorage::TYPE_SAVE);
	if(pPort != nullptr)
	{
		const int Port = str_toint(pPort);
		free(pPort);
		Storage()->RemoveFile(m_aPortFile, IStorage::TYPE_SAVE);
		if(Port > 0 && Port <= 65535)
		{
			m_Port = Port;
			m_WaitingForPort = false;
			m_aLastError[0] = '\0';
			dbg_msg("ranbi_practice", "local practice server ready: port=%d map=%s", m_Port, m_aMapName);
			StartClientB();
			return;
		}
		SetError("practice server reported an invalid port");
		StopServer();
		return;
	}

	if(!ProcessAlive())
	{
		SetError("practice server process exited before reporting its port");
		StopServer();
		return;
	}

	if(Now - m_StartTime > std::chrono::seconds(5))
	{
		SetError("practice server did not report its port within 5 seconds");
		StopServer();
	}
}

bool CRanbiFastPractice::PrepareMapCopy()
{
	const IMap *pMap = GameClient()->Map();
	if(pMap == nullptr || !pMap->IsLoaded())
	{
		SetError("current map is not loaded; practice server not started");
		return false;
	}
	const char *pSourcePath = pMap->Path();
	if(pSourcePath == nullptr || pSourcePath[0] == '\0')
	{
		SetError("current map has no storage path; practice server not started");
		return false;
	}

	void *pData = nullptr;
	unsigned DataSize = 0;
	const int SourceType = fs_is_relative_path(pSourcePath) ? IStorage::TYPE_ALL : IStorage::TYPE_ABSOLUTE;
	if(!Storage()->ReadFile(pSourcePath, SourceType, &pData, &DataSize) || pData == nullptr)
	{
		SetError("could not read the current map file for the practice server");
		return false;
	}

	const SHA256_DIGEST SourceSha = sha256(pData, DataSize);
	if(SourceSha != pMap->Sha256() || (int)DataSize != pMap->Size())
	{
		free(pData);
		SetError("current map file changed while copying; practice server not started");
		return false;
	}

	char aSha[SHA256_MAXSTRSIZE];
	sha256_str(SourceSha, aSha, sizeof(aSha));
	str_format(m_aMapName, sizeof(m_aMapName), "ranbi_practice_%d_%.8s", process_id(), aSha);
	str_format(m_aMapPath, sizeof(m_aMapPath), "maps/%s.map", m_aMapName);
	if(!Storage()->CreateFolder("maps", IStorage::TYPE_SAVE))
	{
		free(pData);
		SetError("could not create the maps folder for the practice server");
		return false;
	}

	Storage()->RemoveFile(m_aMapPath, IStorage::TYPE_SAVE);
	IOHANDLE File = Storage()->OpenFile(m_aMapPath, IOFLAG_WRITE, IStorage::TYPE_SAVE);
	if(!File)
	{
		free(pData);
		SetError("could not write the temporary practice map");
		return false;
	}
	const bool Written = io_write(File, pData, DataSize) == DataSize;
	io_close(File);
	free(pData);

	if(!Written)
	{
		CleanupTempFiles(2);
		SetError("could not write the complete temporary practice map");
		return false;
	}

	// Verify the copied file by reading it back and comparing size + SHA256 with the main map.
	void *pVerify = nullptr;
	unsigned VerifySize = 0;
	const bool ReadBack = Storage()->ReadFile(m_aMapPath, IStorage::TYPE_SAVE, &pVerify, &VerifySize) && pVerify != nullptr;
	const bool Verified = ReadBack && VerifySize == DataSize && sha256(pVerify, VerifySize) == SourceSha;
	free(pVerify);
	if(!Verified)
	{
		CleanupTempFiles(2);
		SetError("temporary practice map failed SHA verification");
		return false;
	}

	// The server also looks for maps/<name>.cfg; make sure our unique temporary name cannot
	// accidentally pick up an unrelated user map config.
	str_format(m_aMapCfgPath, sizeof(m_aMapCfgPath), "maps/%s.cfg", m_aMapName);
	Storage()->RemoveFile(m_aMapCfgPath, IStorage::TYPE_SAVE);

	m_MapSha = SourceSha;
	dbg_msg("ranbi_practice", "copied map '%s' to '%s' (sha256=%s)", pSourcePath, m_aMapPath, aSha);
	return true;
}

bool CRanbiFastPractice::StartServerProcess()
{
#if defined(CONF_PLATFORM_ANDROID)
	SetError("dual-server practice is not implemented on Android yet");
	return false;
#else
	char aBinaryPath[IO_MAX_PATH_LENGTH];
	Storage()->GetBinaryPath(PLAT_SERVER_EXEC, aBinaryPath, sizeof(aBinaryPath));
	if(str_find(aBinaryPath, "/") != nullptr && !fs_is_file(aBinaryPath))
	{
		SetError("DDNet-Server executable not found next to the client");
		return false;
	}

	Storage()->RemoveFile(m_aPortFile, IStorage::TYPE_SAVE);

	std::vector<std::string> vArguments;
	vArguments.emplace_back("sv_register 0");
	vArguments.emplace_back("sv_port 0");
	vArguments.emplace_back("sv_max_clients 2");
	vArguments.emplace_back("sv_max_clients_per_ip 2");
	vArguments.emplace_back(std::string("sv_map ") + m_aMapName);
	vArguments.emplace_back("sv_practice 1");
	vArguments.emplace_back("sv_test_cmds 1");
	vArguments.emplace_back("sv_practice_by_default 1");
	vArguments.emplace_back("sv_team 2");
	vArguments.emplace_back("sv_rescue 1");
	vArguments.emplace_back("sv_pauseable 1");
	vArguments.emplace_back("sv_sixup 0"); // practice is 0.6-only; avoids maps7 load failure
	vArguments.emplace_back("bindaddr 127.0.0.1");
	char aSyncCommand[512];
	str_format(aSyncCommand, sizeof(aSyncCommand), "sv_ranbi_practice_sync_file \"%s\"", m_aGuestSyncFile);
	vArguments.emplace_back(aSyncCommand);

	char aPortFileCommand[160];
	str_format(aPortFileCommand, sizeof(aPortFileCommand), "sv_port_file %s", m_aPortFile);
	vArguments.emplace_back(aPortFileCommand);

	char aAuthCommand[256];
	str_format(aAuthCommand, sizeof(aAuthCommand), "auth_add %s admin %s", DEFAULT_SAVED_RCON_USER, m_aRconPassword);
	vArguments.emplace_back(aAuthCommand);

	std::vector<const char *> vpArguments;
	vpArguments.reserve(vArguments.size());
	for(const std::string &Argument : vArguments)
		vpArguments.push_back(Argument.c_str());

	m_Process = process_execute(aBinaryPath, EShellExecuteWindowState::BACKGROUND, vpArguments.data(), vpArguments.size());
	if(m_Process == INVALID_PROCESS)
	{
		SetError("could not start DDNet-Server for practice mode");
		return false;
	}

#if defined(CONF_FAMILY_WINDOWS)
	// Kill-on-job-close keeps the server from becoming an orphan if the client process exits
	// unexpectedly. If creating/assigning the job fails, OnShutdown/StopServer still kills the
	// process normally, but a crash could leave an orphan (reported as residual risk).
	HANDLE pJob = CreateJobObjectW(nullptr, nullptr);
	if(pJob != nullptr)
	{
		JOBOBJECT_EXTENDED_LIMIT_INFORMATION Info{};
		Info.BasicLimitInformation.LimitFlags = JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE;
		if(SetInformationJobObject(pJob, JobObjectExtendedLimitInformation, &Info, sizeof(Info)) &&
			AssignProcessToJobObject(pJob, static_cast<HANDLE>(m_Process)))
		{
			m_pJobObject = pJob;
		}
		else
		{
			dbg_msg("ranbi_practice", "warning: failed to assign practice server to a job object; crash-orphan protection unavailable");
			CloseHandle(pJob);
		}
	}
	else
	{
		dbg_msg("ranbi_practice", "warning: failed to create job object; crash-orphan protection unavailable");
	}
#endif

	m_Port = 0;
	m_WaitingForPort = true;
	m_StartTime = time_get_nanoseconds();
	m_NextPortCheck = m_StartTime;
	dbg_msg("ranbi_practice", "started local practice server (map=%s), waiting for port", m_aMapName);
	return true;
#endif
}

static void EncodeGuestState(const CCharacter *pCharacter, char *pOut, int OutSize)
{
	if(pCharacter == nullptr)
	{
		str_copy(pOut, "valid=0", OutSize);
		return;
	}
	const CCharacterCore *pCore = pCharacter->Core();
	int GotMask = 0;
	for(int i = 0; i < NUM_WEAPONS; i++)
	{
		if(pCore->m_aWeapons[i].m_Got)
			GotMask |= 1 << i;
	}
	int HitDisabled = 0;
	if(pCore->m_HammerHitDisabled)
		HitDisabled |= 1;
	if(pCore->m_GrenadeHitDisabled)
		HitDisabled |= 2;
	if(pCore->m_LaserHitDisabled)
		HitDisabled |= 4;
	if(pCore->m_ShotgunHitDisabled)
		HitDisabled |= 8;
	if(pCore->m_HookHitDisabled)
		HitDisabled |= 16;
	char aAmmo[64];
	str_format(aAmmo, sizeof(aAmmo), "%d:%d:%d:%d:%d:%d",
		pCore->m_aWeapons[0].m_Ammo, pCore->m_aWeapons[1].m_Ammo, pCore->m_aWeapons[2].m_Ammo,
		pCore->m_aWeapons[3].m_Ammo, pCore->m_aWeapons[4].m_Ammo, pCore->m_aWeapons[5].m_Ammo);
	str_format(pOut, OutSize,
		"valid=1,active=%d,got=%d,jumps=%d,solo=%d,infjump=%d,endless=%d,deep=%d,live=%d,invincible=%d,collision=%d,super=%d,jetpack=%d,ammo=%s,jumptotal=%d,hitdis=%d",
		pCore->m_ActiveWeapon, GotMask, pCore->m_Jumps,
		pCore->m_Solo ? 1 : 0, pCore->m_EndlessJump ? 1 : 0,
		pCore->m_EndlessHook ? 1 : 0, pCore->m_DeepFrozen ? 1 : 0,
		pCore->m_LiveFrozen ? 1 : 0, pCore->m_Invincible ? 1 : 0,
		pCore->m_CollisionDisabled ? 1 : 0, pCore->m_Super ? 1 : 0,
		pCore->m_Jetpack ? 1 : 0, aAmmo, pCore->m_JumpedTotal, HitDisabled);
}

void CRanbiFastPractice::CaptureGuestStartData()
{
	m_GuestBodyPos = vec2(0.0f, 0.0f);
	m_GuestDummyPos = vec2(0.0f, 0.0f);
	m_GuestHasDummy = false;
	const int BodyId = GameClient()->m_aLocalIds[0];
	if(BodyId >= 0 && BodyId < MAX_CLIENTS)
		m_GuestBodyPos = GameClient()->m_aClients[BodyId].m_RenderPos;
	const int DummyId = GameClient()->m_aLocalIds[1];
	if(Client()->DummyConnected() && DummyId >= 0 && DummyId < MAX_CLIENTS)
	{
		m_GuestHasDummy = true;
		m_GuestDummyPos = GameClient()->m_aClients[DummyId].m_RenderPos;
		if(m_GuestDummyPos == vec2(0.0f, 0.0f))
		{
			const CCharacter *pDummy = GameClient()->m_PredictedWorld.GetCharacterById(DummyId);
			if(pDummy == nullptr)
				pDummy = GameClient()->m_GameWorld.GetCharacterById(DummyId);
			if(pDummy != nullptr)
				m_GuestDummyPos = pDummy->Core()->m_Pos;
			else
				m_GuestDummyPos = GameClient()->m_aClients[DummyId].m_Predicted.m_Pos;
		}
	}
	dbg_msg("ranbi_practice", "capture: cl_dummy=%d body_id=%d bodypos=(%.3f,%.3f) had_dummy=%d dummy_id=%d dummypos=(%.3f,%.3f)",
		g_Config.m_ClDummy, BodyId, m_GuestBodyPos.x, m_GuestBodyPos.y,
		m_GuestHasDummy ? 1 : 0, DummyId, m_GuestDummyPos.x, m_GuestDummyPos.y);
	str_copy(m_aGuestBodyState, "valid=0", sizeof(m_aGuestBodyState));
	str_copy(m_aGuestDummyState, "valid=0", sizeof(m_aGuestDummyState));
	if(BodyId >= 0 && BodyId < MAX_CLIENTS)
	{
		const CCharacter *pBody = GameClient()->m_PredictedWorld.GetCharacterById(BodyId);
		if(pBody == nullptr)
			pBody = GameClient()->m_GameWorld.GetCharacterById(BodyId);
		EncodeGuestState(pBody, m_aGuestBodyState, sizeof(m_aGuestBodyState));
	}
	if(m_GuestHasDummy && DummyId >= 0 && DummyId < MAX_CLIENTS)
	{
		const CCharacter *pDummy = GameClient()->m_PredictedWorld.GetCharacterById(DummyId);
		if(pDummy == nullptr)
			pDummy = GameClient()->m_GameWorld.GetCharacterById(DummyId);
		EncodeGuestState(pDummy, m_aGuestDummyState, sizeof(m_aGuestDummyState));
	}
	dbg_msg("ranbi_practice", "guest start data: body=(%.3f,%.3f) dummy=%d dummypos=(%.3f,%.3f) body_state=%s dummy_state=%s",
		m_GuestBodyPos.x, m_GuestBodyPos.y, m_GuestHasDummy ? 1 : 0, m_GuestDummyPos.x, m_GuestDummyPos.y,
		m_aGuestBodyState, m_aGuestDummyState);
}

bool CRanbiFastPractice::WriteGuestSyncFile()
{
	CleanupGuestSyncFile();
	char aName[128];
	str_format(aName, sizeof(aName), "ranbi_practice_sync_%d.txt", process_id());
	Storage()->GetCompletePath(IStorage::TYPE_SAVE, aName, m_aGuestSyncFile, sizeof(m_aGuestSyncFile));
	if(m_aGuestSyncFile[0] == '\0')
	{
		dbg_msg("ranbi_practice", "warning: could not build guest sync file path");
		return false;
	}

	IOHANDLE File = Storage()->OpenFile(m_aGuestSyncFile, IOFLAG_WRITE, IStorage::TYPE_ABSOLUTE);
	if(!File)
	{
		dbg_msg("ranbi_practice", "warning: could not write guest sync file '%s'", m_aGuestSyncFile);
		m_aGuestSyncFile[0] = '\0';
		return false;
	}
	char aBuffer[2048];
	const int Len = str_format(aBuffer, sizeof(aBuffer),
		"has_dummy=%d\n"
		"body_pos=%.3f,%.3f\n"
		"dummy_pos=%.3f,%.3f\n"
		"body_state=%s\n"
		"dummy_state=%s\n",
		m_GuestHasDummy ? 1 : 0,
		m_GuestBodyPos.x, m_GuestBodyPos.y,
		m_GuestDummyPos.x, m_GuestDummyPos.y,
		m_aGuestBodyState, m_aGuestDummyState);
	io_write(File, aBuffer, Len);
	io_close(File);
	dbg_msg("ranbi_practice", "wrote guest sync file '%s'", m_aGuestSyncFile);
	return true;
}

void CRanbiFastPractice::CleanupGuestSyncFile()
{
	if(m_aGuestSyncFile[0] != '\0')
	{
		Storage()->RemoveFile(m_aGuestSyncFile, IStorage::TYPE_ABSOLUTE);
		m_aGuestSyncFile[0] = '\0';
	}
}

void CRanbiFastPractice::InitChatFiles()
{
	CleanupChatFiles();
	char aName[160];
	str_format(aName, sizeof(aName), "ranbi_practice_chat_%d_a2b.txt", process_id());
	Storage()->GetCompletePath(IStorage::TYPE_SAVE, aName, m_aChatA2B, sizeof(m_aChatA2B));
	str_format(aName, sizeof(aName), "ranbi_practice_chat_%d_b2a.txt", process_id());
	Storage()->GetCompletePath(IStorage::TYPE_SAVE, aName, m_aChatB2A, sizeof(m_aChatB2A));
	if(m_aChatA2B[0] != '\0')
	{
		IOHANDLE File = Storage()->OpenFile(m_aChatA2B, IOFLAG_WRITE, IStorage::TYPE_ABSOLUTE);
		if(File)
			io_close(File);
	}
	if(m_aChatB2A[0] != '\0')
	{
		IOHANDLE File = Storage()->OpenFile(m_aChatB2A, IOFLAG_WRITE, IStorage::TYPE_ABSOLUTE);
		if(File)
			io_close(File);
	}
	dbg_msg("ranbi_practice", "chat IPC files: a2b='%s' b2a='%s'", m_aChatA2B, m_aChatB2A);
}

void CRanbiFastPractice::CleanupChatFiles()
{
	if(m_aChatA2B[0] != '\0')
	{
		Storage()->RemoveFile(m_aChatA2B, IStorage::TYPE_ABSOLUTE);
		m_aChatA2B[0] = '\0';
	}
	if(m_aChatB2A[0] != '\0')
	{
		Storage()->RemoveFile(m_aChatB2A, IStorage::TYPE_ABSOLUTE);
		m_aChatB2A[0] = '\0';
	}
}

void CRanbiFastPractice::RelayChatLine(int ClientId, const char *pLine)
{
	if(pLine == nullptr || pLine[0] == '\0' || m_aChatA2B[0] == '\0')
		return;
	if(g_Config.m_RcRanbiFastPractice == 0 || g_Config.m_RcRanbiPracticeGuest != 0 || !IsServerRunning())
		return;
	char aLine[1024];
	if(ClientId >= 0 && ClientId < MAX_CLIENTS && GameClient()->m_aClients[ClientId].m_aName[0] != '\0')
		str_format(aLine, sizeof(aLine), "[%s] %s", GameClient()->m_aClients[ClientId].m_aName, pLine);
	else
		str_format(aLine, sizeof(aLine), "[Server] %s", pLine);
	IOHANDLE File = Storage()->OpenFile(m_aChatA2B, IOFLAG_APPEND, IStorage::TYPE_ABSOLUTE);
	if(!File)
		return;
	io_write(File, aLine, str_length(aLine));
	io_write(File, "\n", 1);
	io_close(File);
}

void CRanbiFastPractice::PollHostChat()
{
	if(m_aChatB2A[0] == '\0')
		return;
	const auto Now = time_get_nanoseconds();
	if(Now < m_NextChatPoll)
		return;
	m_NextChatPoll = Now + std::chrono::milliseconds(200);
	char *pData = const_cast<char *>(Storage()->ReadFileStr(m_aChatB2A, IStorage::TYPE_ABSOLUTE));
	if(pData == nullptr)
		return;
	char *pCursor = pData;
	while(pCursor != nullptr && *pCursor != '\0')
	{
		char *pEnd = const_cast<char *>(str_find(pCursor, "\n"));
		if(pEnd != nullptr)
			*pEnd = '\0';
		if(*pCursor != '\0')
			GameClient()->m_Chat.SendChat(0, pCursor);
		pCursor = pEnd != nullptr ? pEnd + 1 : nullptr;
	}
	free(pData);
	Storage()->RemoveFile(m_aChatB2A, IStorage::TYPE_ABSOLUTE);
}

bool CRanbiFastPractice::ClientBAlive() const
{
#if !defined(CONF_PLATFORM_ANDROID)
	return m_ClientBProcess != INVALID_PROCESS && process_is_alive(m_ClientBProcess);
#else
	return false;
#endif
}

void CRanbiFastPractice::ReapClientB()
{
#if !defined(CONF_PLATFORM_ANDROID)
	if(m_ClientBProcess == INVALID_PROCESS)
		return;
	if(process_is_alive(m_ClientBProcess))
		return;
	dbg_msg("ranbi_practice", "practice guest client exited");
#if defined(CONF_FAMILY_WINDOWS)
	CloseHandle(static_cast<HANDLE>(m_ClientBProcess));
	if(m_pClientBJobObject != nullptr)
	{
		CloseHandle(static_cast<HANDLE>(m_pClientBJobObject));
		m_pClientBJobObject = nullptr;
	}
#endif
	m_ClientBProcess = INVALID_PROCESS;
	if(!m_StoppingClientB && g_Config.m_RcRanbiFastPractice != 0)
	{
		// B exited on its own (Stop practice in B / crash): close A's practice too.
		dbg_msg("ranbi_practice", "guest exited while practice enabled; auto-closing A");
		g_Config.m_RcRanbiFastPractice = 0;
		m_WasEnabled = false;
		StopServer();
	}
#endif
}

void CRanbiFastPractice::StartClientB()
{
#if defined(CONF_PLATFORM_ANDROID)
	return;
#else
	if(m_ClientBStarted || m_Port <= 0)
		return;
	m_ClientBStarted = true;
	InitChatFiles();

	char aBinaryPath[IO_MAX_PATH_LENGTH];
	Storage()->GetBinaryPath(PLAT_CLIENT_EXEC, aBinaryPath, sizeof(aBinaryPath));
	if(str_find(aBinaryPath, "/") != nullptr && !fs_is_file(aBinaryPath))
	{
		dbg_msg("ranbi_practice", "warning: DDNet client executable not found; practice guest not started");
		return;
	}

	char aConnect[64];
	str_format(aConnect, sizeof(aConnect), "connect 127.0.0.1:%d", m_Port);
	char aBody[96];
	str_format(aBody, sizeof(aBody), "rc_ranbi_practice_guest_body_pos %.3f,%.3f", m_GuestBodyPos.x / 32.0f, m_GuestBodyPos.y / 32.0f);
	char aDummyPos[96];
	str_format(aDummyPos, sizeof(aDummyPos), "rc_ranbi_practice_guest_dummy_pos %.3f,%.3f", m_GuestDummyPos.x / 32.0f, m_GuestDummyPos.y / 32.0f);

	std::vector<std::string> vArguments;
	vArguments.emplace_back("-s");
	vArguments.emplace_back("rc_ranbi_fast_practice 0");
	vArguments.emplace_back("rc_ranbi_practice_guest 1");
	vArguments.emplace_back(aBody);
	vArguments.emplace_back(m_GuestHasDummy ? "rc_ranbi_practice_guest_dummy 1" : "rc_ranbi_practice_guest_dummy 0");
	vArguments.emplace_back(aDummyPos);
	vArguments.emplace_back(std::string("rc_ranbi_practice_guest_body_state ") + m_aGuestBodyState);
	vArguments.emplace_back(std::string("rc_ranbi_practice_guest_dummy_state ") + m_aGuestDummyState);
	vArguments.emplace_back("cl_save_settings 0");
	vArguments.emplace_back("logfile \"\"");
	vArguments.emplace_back("cl_input_fifo \"\"");
	vArguments.emplace_back("bc_discord_rpc 0");
	vArguments.emplace_back(aConnect);
	char aChatPid[64];
	str_format(aChatPid, sizeof(aChatPid), "rc_ranbi_practice_guest_chat_pid %d", process_id());
	vArguments.emplace_back(aChatPid);

	std::vector<const char *> vpArguments;
	vpArguments.reserve(vArguments.size());
	for(const std::string &Argument : vArguments)
		vpArguments.push_back(Argument.c_str());

	m_ClientBProcess = process_execute(aBinaryPath, EShellExecuteWindowState::FOREGROUND_NOACTIVATE, vpArguments.data(), vpArguments.size());
	if(m_ClientBProcess == INVALID_PROCESS)
	{
		dbg_msg("ranbi_practice", "warning: could not start practice guest client");
		return;
	}
	dbg_msg("ranbi_practice", "started practice guest client B (port=%d dummy=%d)", m_Port, m_GuestHasDummy ? 1 : 0);

#if defined(CONF_FAMILY_WINDOWS)
	HANDLE pJob = CreateJobObjectW(nullptr, nullptr);
	if(pJob != nullptr)
	{
		JOBOBJECT_EXTENDED_LIMIT_INFORMATION Info{};
		Info.BasicLimitInformation.LimitFlags = JOB_OBJECT_LIMIT_KILL_ON_JOB_CLOSE;
		if(SetInformationJobObject(pJob, JobObjectExtendedLimitInformation, &Info, sizeof(Info)) &&
			AssignProcessToJobObject(pJob, static_cast<HANDLE>(m_ClientBProcess)))
		{
			m_pClientBJobObject = pJob;
		}
		else
		{
			CloseHandle(pJob);
		}
	}
#endif
#endif
}

void CRanbiFastPractice::StopClientB()
{
	m_StoppingClientB = true;
#if !defined(CONF_PLATFORM_ANDROID)
	if(m_ClientBProcess != INVALID_PROCESS)
	{
#if defined(CONF_FAMILY_WINDOWS)
		HANDLE pProcess = static_cast<HANDLE>(m_ClientBProcess);
		TerminateProcess(pProcess, 0);
		WaitForSingleObject(pProcess, 500);
		CloseHandle(pProcess);
		if(m_pClientBJobObject != nullptr)
		{
			CloseHandle(static_cast<HANDLE>(m_pClientBJobObject));
			m_pClientBJobObject = nullptr;
		}
#else
		process_kill(m_ClientBProcess);
#endif
		m_ClientBProcess = INVALID_PROCESS;
	}
#endif
	m_ClientBStarted = false;
	m_StoppingClientB = false;
}

void CRanbiFastPractice::TryStartServer()
{
	m_aLastError[0] = '\0';
	if(g_Config.m_RcRanbiPracticeGuest != 0)
	{
		SetError("guest client does not start a practice server");
		return;
	}
	m_aRconPassword[0] = '\0';
	m_Port = 0;
	m_WaitingForPort = false;
	m_KillFailed = false;
	CleanupStalePidFiles();

	if(Client()->State() != IClient::STATE_ONLINE)
	{
		SetError("main client is not online; practice server not started");
		return;
	}
	if(!GameClient()->Map()->IsLoaded())
	{
		SetError("main map is not loaded; practice server not started");
		return;
	}

	CaptureGuestStartData();
	if(!WriteGuestSyncFile())
	{
		SetError("could not write practice sync file");
		return;
	}
	const auto Now = time_get_nanoseconds();
	PracticePortFile(m_aPortFile, sizeof(m_aPortFile));
	secure_random_password(m_aRconPassword, sizeof(m_aRconPassword), 16);

	if(!PrepareMapCopy())
	{
		StopServer();
		return;
	}
	if(!StartServerProcess())
	{
		StopServer();
		return;
	}

	// Wait is driven by OnUpdate/UpdatePort.
	(void)Now;
}

void CRanbiFastPractice::OnUpdate()
{
	ReapExitedProcess();
	ReapClientB();
	RetryPendingCleanup();
	PollHostChat();

	if(g_Config.m_RcRanbiPracticeGuest != 0)
	{
		// Guest clients must never start a nested local server / second guest.
		if(m_WasEnabled || ProcessAlive() || ClientBAlive())
			StopServer();
		m_WasEnabled = false;
		m_StartAttempted = false;
		return;
	}

	const bool Enabled = g_Config.m_RcRanbiFastPractice != 0;
	if(!Enabled)
	{
		if(m_WasEnabled || m_WaitingForPort || ProcessAlive() || m_Port > 0)
		{
			// Avoid re-entering a blocking kill attempt every frame if it failed once.
			if(!m_KillFailed)
				StopServer();
			else
				RetryPendingCleanup();
		}
		m_WasEnabled = false;
		m_StartAttempted = false;
		return;
	}
	if(!m_WasEnabled)
	{
		// Feature was just enabled: allow a fresh start attempt.
		m_WasEnabled = true;
		m_StartAttempted = false;
	}

	if(!m_Online)
		return;

	if(m_WaitingForPort)
	{
		UpdatePort();
		return;
	}

	if(ProcessAlive())
		return;

	if(m_Port > 0 || m_StartAttempted)
	{
		if(m_Port > 0)
		{
			SetError("practice server exited unexpectedly");
			StopServer();
		}
		return;
	}

	if(Client()->State() != IClient::STATE_ONLINE || !GameClient()->Map()->IsLoaded())
		return;

	m_StartAttempted = true;
	TryStartServer();
}
